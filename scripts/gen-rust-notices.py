# Lists every crate linked into libpf_switch.a with its declared license, from `cargo metadata`.
#   scripts/dev.sh python3 scripts/gen-rust-notices.py > licenses/rust-crates.md
import json
import subprocess
import sys
from pathlib import Path

RS = Path(__file__).resolve().parent.parent / "punktfunk-rs"

meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=RS
    )
)
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}

root = next(p["id"] for p in meta["packages"] if p["name"] == "pf-switch")
seen, stack = set(), [root]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        # Build scripts and proc macros never reach the binary.
        if any(k["kind"] in (None, "normal") for k in dep["dep_kinds"]):
            stack.append(dep["pkg"])

own = set(meta["workspace_members"])
rows = sorted(
    (packages[pid] for pid in seen if pid not in own),
    key=lambda p: (p["name"], p["version"]),
)

out = sys.stdout
out.write("# Rust crates in libpf_switch.a\n\n")
out.write(
    "Generated by `scripts/gen-rust-notices.py` from `punktfunk-rs/Cargo.lock`. Crates patched for\n"
    "Horizon (libc, mio, tokio, getrandom, if-addrs, quinn-udp, aws-lc-sys) keep their upstream\n"
    "licenses; their full texts ship inside each crate under `punktfunk-rs/patches/`.\n\n"
)
out.write("| Crate | Version | License | Repository |\n|---|---|---|---|\n")
for p in rows:
    lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "unknown")
    repo = p.get("repository") or ""
    out.write(f"| {p['name']} | {p['version']} | {lic} | {repo} |\n")
